# Writes src/model/print/stl-font.ts: Noto Sans Bold outlines for the 3D template text (spec 027).
# uv run -q --with fonttools --with shapely python -I scripts/stl-font.py /usr/share/fonts/truetype/noto/NotoSans-Bold.ttf src/model/print/stl-font.ts
import json, math, sys
from fontTools.ttLib import TTFont
from fontTools.pens.basePen import BasePen
from shapely.geometry import Polygon
font = TTFont(sys.argv[1]); gs = font.getGlyphSet(); cmap = font.getBestCmap()
name = font['name']
copyright = name.getDebugName(0); license_url = name.getDebugName(14)
upm = font['head'].unitsPerEm; TOL = 3.0
class Flat(BasePen):
    def __init__(s, gs): super().__init__(gs); s.cs = []; s.cur = None
    def _moveTo(s, p): s.cur = [p]; s.cs.append(s.cur)
    def _lineTo(s, p): s.cur.append(p)
    def _qCurveToOne(s, p1, p2):
        p0 = s.cur[-1]; d = math.hypot(p0[0] - 2 * p1[0] + p2[0], p0[1] - 2 * p1[1] + p2[1])
        n = max(1, math.ceil(math.sqrt(d / (8 * TOL))))
        for k in range(1, n + 1):
            t = k / n; u = 1 - t
            s.cur.append((u*u*p0[0] + 2*u*t*p1[0] + t*t*p2[0], u*u*p0[1] + 2*u*t*p1[1] + t*t*p2[1]))
    def _curveToOne(s, p1, p2, p3):
        p0 = s.cur[-1]
        for k in range(1, 9):
            t = k / 8; u = 1 - t
            s.cur.append(tuple(u**3*p0[i] + 3*u*u*t*p1[i] + 3*u*t*t*p2[i] + t**3*p3[i] for i in (0, 1)))
    def _closePath(s): pass
def area(p): return sum(p[i][0] * p[(i+1) % len(p)][1] - p[(i+1) % len(p)][0] * p[i][1] for i in range(len(p))) / 2
def clean(p):
    p = [q for i, q in enumerate(p) if math.dist(q, p[i-1]) > 0.05]
    return [b for i, b in enumerate(p) if abs((b[0]-p[i-1][0])*(p[(i+1)%len(p)][1]-b[1]) - (b[1]-p[i-1][1])*(p[(i+1)%len(p)][0]-b[0])) > 1e-6 * max(1, math.dist(p[i-1], p[(i+1)%len(p)]))]
enc = lambda c: ' '.join(f'{round(x)},{round(y)}' for x, y in c)
glyphs = {}
for ch in sorted(set('Edge: Size SA: 0123456789/".m×')):
    g = cmap[ord(ch)]; pen = Flat(gs); gs[g].draw(pen)
    cs = [clean(c) for c in pen.cs if len(c) > 2]
    cs = [c if area(c) > 0 else c[::-1] for c in cs]
    polys = [Polygon(c) for c in cs]
    depth = [sum(1 for j, q in enumerate(polys) if j != i and q.contains(polys[i])) for i in range(len(cs))]
    assert max(depth, default=0) <= 1, ch
    shapes = []
    for i, c in enumerate(cs):
        if depth[i]: continue
        holes = [cs[j] for j in range(len(cs)) if depth[j] == 1 and polys[i].contains(polys[j])]
        assert Polygon(c, holes).is_valid, ch
        shapes.append([enc(c)] + [enc(h) for h in holes])
    outs = [Polygon(s[0].split(' ') and [tuple(map(float, q.split(','))) for q in s[0].split(' ')]) for s in shapes]
    assert all(not outs[i].intersects(outs[j]) for i in range(len(outs)) for j in range(i + 1, len(outs))), ch
    glyphs[ch] = {'adv': gs[g].width, 'shapes': shapes}
lines = [
    '// Glyph outlines for the text on 3D-printed templates: the characters of `Edge: 1 1/2"`,',
    '// `Size: 2" × 3"`, `SA: 3/8"` and mm, from Noto Sans Bold, curves flattened (font units, y up).',
    f'// {copyright}',
    f'// Licensed under the SIL Open Font License, Version 1.1 ({license_url}).',
    '// Each shape: an outline, then its holes, as "x,y x,y ..." strings, all counter-clockwise.',
    '// Generated by scripts/stl-font.py from NotoSans-Bold.ttf; do not hand-edit.',
    '',
    'export interface StlFont {',
    '  upm: number;',
    '  glyphs: Record<string, { adv: number; shapes: string[][] }>;',
    '}',
    '',
    f'export const STL_FONT: StlFont = {{',
    f'  upm: {upm},',
    '  glyphs: {',
]
for ch, g in glyphs.items():
    lines.append(f'    {json.dumps(ch, ensure_ascii=False)}: {{')
    lines.append(f'      adv: {g["adv"]},')
    lines.append('      shapes: [')
    for s in g['shapes']:
        lines.append('        [')
        for part in s: lines.append(f'          {json.dumps(part)},')
        lines.append('        ],')
    lines.append('      ],')
    lines.append('    },')
lines += ['  },', '};', '']
open(sys.argv[2], 'w').write('\n'.join(lines))
print(copyright, '|', license_url, '|', len(glyphs), 'glyphs')
